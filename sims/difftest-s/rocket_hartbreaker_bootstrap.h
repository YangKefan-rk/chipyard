#ifndef CHIPYARD_DIFFTEST_S_ROCKET_HARTBREAKER_BOOTSTRAP_H
#define CHIPYARD_DIFFTEST_S_ROCKET_HARTBREAKER_BOOTSTRAP_H

#include <array>
#include <cstddef>
#include <cstdint>
#include <stdexcept>

namespace difftest_s::native {

// Only the exact HartBreaker quadrocket timer-disable prefix is excluded. Its
// sole memory effect is a per-hart CLINT mtimecmp write, outside checked RAM.
// All later instructions, including CSR setup, enter the normal REF/PPO path.
struct HartbreakerBootstrapCheckpoint {
  uint64_t pc = 0;
  std::array<uint64_t, 32> gpr{};
  std::array<bool, 32> initialized{};
};

template <typename Memory>
HartbreakerBootstrapCheckpoint hartbreaker_bootstrap_checkpoint(const Memory &memory, uint64_t entry,
                                                                uint32_t hart) {
  if (entry != UINT64_C(0x80000000) || hart >= 4)
    throw std::invalid_argument("HartBreaker bootstrap requires quadrocket RAM entry and hart 0..3");

  // Exact ISA bytes generated by HartBreaker: independent integer setup,
  // mhartid, and sd -1 to CLINT mtimecmp[hart]. Reject any other code rather
  // than treating an unknown bootstrap store as an unchecked side effect.
  constexpr std::array<uint32_t, 16> expected = {
      0x00100f93, 0x01ff9f93, 0xfff00f13, 0x020f5f13,
      0x00180d37, 0x018d0d13, 0x01fd0d33, 0x00006eb7,
      0x002ede13, 0x020040b7, 0x01e0f0b3, 0xf14021f3,
      0x00319193, 0x001180b3, 0xfff00113, 0x0020b023};
  for (size_t index = 0; index < expected.size(); ++index) {
    std::array<uint8_t, 4> bytes{};
    if (!memory.read(entry + 4 * index, bytes.data(), bytes.size()))
      throw std::invalid_argument("HartBreaker bootstrap instruction is absent from independent ELF image");
    uint32_t instruction = 0;
    for (size_t byte = 0; byte < bytes.size(); ++byte)
      instruction |= static_cast<uint32_t>(bytes[byte]) << (byte * 8);
    if (instruction != expected[index])
      throw std::invalid_argument("unsupported HartBreaker bootstrap opcode or CLINT timer address");
  }

  HartbreakerBootstrapCheckpoint checkpoint;
  checkpoint.pc = entry + expected.size() * 4;
  checkpoint.initialized[0] = true;
  checkpoint.initialized[1] = true;
  checkpoint.initialized[2] = true;
  checkpoint.initialized[3] = true;
  checkpoint.initialized[26] = true;
  checkpoint.initialized[28] = true;
  checkpoint.initialized[29] = true;
  checkpoint.initialized[30] = true;
  checkpoint.initialized[31] = true;
  checkpoint.gpr[31] = UINT64_C(0x80000000);
  checkpoint.gpr[30] = UINT64_C(0x00000000ffffffff);
  checkpoint.gpr[26] = UINT64_C(0x80180018);
  checkpoint.gpr[29] = UINT64_C(0x6000);
  checkpoint.gpr[28] = UINT64_C(0x1800);
  checkpoint.gpr[3] = static_cast<uint64_t>(hart) * 8;
  checkpoint.gpr[1] = UINT64_C(0x02004000) + checkpoint.gpr[3];
  checkpoint.gpr[2] = UINT64_MAX;
  return checkpoint;
}

} // namespace difftest_s::native
#endif
